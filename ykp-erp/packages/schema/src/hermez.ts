export const actionPriorityEnum = hermez.enum("hermez_action_priority", [
  "LOW",
  "MEDIUM",
  "HIGH",
  "CRITICAL",
]);

export const actionStatusEnum = hermez.enum("hermez_action_status", [
  "OPEN",
  "IN_PROGRESS",
  "WAITING_APPROVAL",
  "DONE",
  "CANCELLED",
  "OVERDUE",
]);

// ============================================================
// hermez_action_tracker
// action_id is generated by the app layer following HZAC-YYYYMMDD-NNN.
// ============================================================

export const hermezActionTracker = hermez.table("hermez_action_tracker", {
  actionId: text("action_id").primaryKey(),
  sourceAlertId: text("source_alert_id"),
  title: text("title").notNull(),
  brand: text("brand"),
  outlet: text("outlet"),
  assignedTo: text("assigned_to"),
  priority: actionPriorityEnum("priority").notNull().default("MEDIUM"),
  dueDate: date("due_date", { mode: "date" }),
  status: actionStatusEnum("status").notNull().default("OPEN"),
  actionTaken: text("action_taken"),
  createdAt: timestamp("created_at", { mode: "date" }).defaultNow().notNull(),
  completedAt: timestamp("completed_at", { mode: "date" }),
});

// ============================================================
// Inferred types (action tracker)
// ============================================================

export type HermezActionTracker = typeof hermezActionTracker.$inferSelect;
